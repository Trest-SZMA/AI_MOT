def classify_family(name: str) -> str | None:
    for family, pattern in FAMILY_PATTERNS:
        if pattern.search(name):
            return family
    return None


# ---------------------------------------------------------------- типоразмеры

_SCRAP_RE = re.compile(r"\bлом\b|металлолом|вторсыр|стружк|окалин|\(лом\)", re.I)


def is_scrap(name: str) -> bool:
    """Ломовая ли позиция. Ломовую и деловую карточки нельзя сопоставлять:
    «аккумуляторных батарей ТНЖШ-350» садилось на «Лом аккумуляторных
    батарей (кг)» и получало 44 ₽/кг вместо цены изделия."""
    return bool(_SCRAP_RE.search(normalize_name(name)))


_SIZE_NKT = re.compile(r"нкт\D{0,3}(\d{2,3})", re.I)
_SIZE_PIPE = re.compile(r"труба\D{0,3}(\d{2,4})", re.I)

# Модельные ряды, у которых первое число после марки — габарит (мощность),
# главный ценообразующий признак. Порядок альтернатив важен: длинные марки
# раньше коротких, иначе «ВВДМ» распадётся на «В» + «ВДМ».
# Ведущая группа цифр — обозначение габарита корпуса в 1С («10ВДМ100» —
# та же машина, что «ВДМ 100-…-117В5»), её снимаем.
_SERIES_RE = re.compile(
    r"(?:\d{1,2})?"
    r"(ввдм|вдм|пэдн|пэда|пэдб|пэд|эдбвк|эдб|тнжш|тнж|тмпн)"
    r"[\s\-–—]*(\d{1,4})",
    re.I)

# Ряды, внутри которых цены сопоставимы: ВВДМ считаем отдельной серией —
# это другая конструкция, цены с ВДМ не смешиваем.
SERIES_FAMILY = {
    "вдм": "ПЭД", "ввдм": "ПЭД", "пэд": "ПЭД", "пэдн": "ПЭД",
    "пэда": "ПЭД", "пэдб": "ПЭД", "эдб": "ПЭД", "эдбвк": "ПЭД",
    "тнжш": "аккумуляторы", "тнж": "аккумуляторы",
    "тмпн": "трансформатор",
}


def series_key(name: str) -> tuple[str, float] | None:
    """«Погружной электродвигатель 10ВДМ100-2400-3,0-117 (шт)» → («вдм», 100).

    Возвращает (марка, габарит). Габарит — первое число после марки: у ПЭД/ВДМ
    это мощность, у ТНЖШ — ёмкость, у ТМПН — мощность кВА. Именно по нему
    цена меняется в разы внутри одного ряда, поэтому медиана «по семейству»
    для таких позиций бессмысленна.
    """
    n = normalize_name(name)
    m = _SERIES_RE.search(n)
    if not m:
        return None
    size = float(m.group(2))
    if size <= 0:
        return None
    return m.group(1).lower(), size


def extract_size_key(name: str) -> str | None:
    """«НКТ-73…» → «нкт-73»; «Труба 114х7» → «труба-114»; ВДМ 100 → «вдм-100»."""
    n = normalize_name(name)
    m = _SIZE_NKT.search(n)
    if m:
        return f"нкт-{m.group(1)}"
    m = _SIZE_PIPE.search(n)
    if m:
        return f"труба-{m.group(1)}"
    # У лома типоразмер модельного ряда не имеет смысла: «Лом аккумуляторных
    # батарей ТНЖШ-350» стоит как никельсодержащий лом, а не как батарея.
    # Без этой оговорки ломовые продажи попадали в выборку цен изделий.
    sk = series_key(name)
    if sk and not is_scrap(name):
        return f"{sk[0]}-{sk[1]:g}"
    return None




# ---------------------------------------------------------------- марки лома

# маппинг марок лома → материал (из реальных файлов «Выходы металлов»)
SCRAP_GRADE_MATERIAL: dict[str, str] = {
    "3А": "чермет",
    "5А": "чермет",
    "12А": "чермет",
    "20А": "чермет",
    "16АЦ": "16АЦ",  # оцинкованная полоса/броня
    "М5": "медь",
    "Л14": "латунь",
    "Л21": "латунь",
    "А2": "алюминий",
    "А18": "алюминий",
    "Б26": "нержавейка",
}

_GRADE_RE = re.compile(r"(3А|5А|12А|20А|16АЦ|М5|Л14|Л21|А2|А18|Б26)", re.I)


def grade_header_material(header: str) -> str | None:
    """Заголовок колонки марок → материал.

    Реальные варианты: «12А», «Л14, Л21», «Б26 (нирезист)», «Б26 10%».
    """
    h = str(header).strip().upper().replace("A", "А")  # латиница → кириллица
    if "НИРЕЗИСТ" in h:
        return "нержавейка"
    m = _GRADE_RE.search(h)
    if m:
        return SCRAP_GRADE_MATERIAL.get(m.group(1).upper())
    return None


# ---------------------------------------------------------------- единицы

UNIT_FAMILIES = {
    "шт": ("count", 1.0),
    "штука": ("count", 1.0),
    "компл": ("count", 1.0),
    "кг": ("mass", 1.0),
    "т": ("mass", 1000.0),
    "тн": ("mass", 1000.0),
    "тонна": ("mass", 1000.0),
    "г": ("mass", 0.001),
    "м": ("length", 1.0),
    "км": ("length", 1000.0),
    "пог.м": ("length", 1.0),
}


def unit_info(unit: str | None) -> tuple[str, float] | None:
    if not unit:
        return None
    return UNIT_FAMILIES.get(str(unit).strip().lower().rstrip("."))


def convert_quantity(qty: float, from_unit: str, to_unit: str) -> float | None:
    """Конвертация в пределах одного семейства единиц; None — несовместимы."""
    fi, ti = unit_info(from_unit), unit_info(to_unit)
    if not fi or not ti or fi[0] != ti[0]:
        return None
    return qty * fi[1] / ti[1]


# ---------------------------------------------------------------- модельный ключ

# Слова, не несущие идентичности изделия: в справочнике 1С и в перечнях
# продавцов они ставятся в разном порядке и с разной пунктуацией.
_NOISE_WORDS = {
    "б/у", "бу", "new", "новый", "новая", "новое",
    "шт", "штука", "штук", "тн", "т", "кг", "км", "м", "компл", "комплект",
    "секция", "секц", "насосная", "насосный", "насоса", "насос",
    "изделие", "поз", "ед", "ед.изм", "прочее", "тип",
    # Родовое название изделия: в 1С одна и та же машина заведена и как
    # «Погружной электродвигатель ВДМ 80-2400-3.0-117В5 б/у», и просто как
    # «ВДМ 80-2400-3.0-117В5 б/у» — цена продажи лежала на одной карточке,
    # закупка на другой, и ни одна не видела другую.
    "погружной", "погружная", "погружное", "погружный",
    "электродвигатель", "электродвигателя", "двигатель", "двигателя",
}
_ALNUM_RE = re.compile(r"[^a-zа-я0-9]")
_NUM_UNIT_RE = re.compile(r"(\d)\s+(мм|см|м|км)\b\.?")
# Обозначение габарита корпуса перед маркой: «10ВДМ100» и «ВДМ 100» —
# одна машина. Снимаем только перед известными марками, чтобы не тронуть
# типоразмеры вроде «12А» или «30с41нж».
_SERIES_PREFIX_RE = re.compile(
    r"\b\d{1,2}(?=(?:ввдм|вдм|пэдн|пэда|пэдб|пэд|эдбвк|эдб)\d)", re.I)
# Хвост «В5» в обозначении корпуса 117В5 — та же машина, что «…-117».
_HOUSING_TAIL_RE = re.compile(r"(?<=\d)в5\b", re.I)


def model_key(name: str) -> str:
    """Идентичность изделия без порядка слов, пробелов и пунктуации.

    «Секция насосная 1ЭЦНД5-30, 3м б/у» и «1ЭЦНД5-30 б/у (3 м.)» дают один
    ключ «1эцнд5303м» — именно так одна и та же позиция записана в перечне
    продавца и в справочнике 1С.
    """
    norm = normalize_name(name)
    # «(3 м.)» и «3м» — одна и та же длина секции: склеиваем число с единицей,
    # иначе одинокая «м» уйдёт в шум и ключи разойдутся
    norm = _NUM_UNIT_RE.sub(r"\1\2", norm)
    norm = _SERIES_PREFIX_RE.sub("", norm)
    norm = _HOUSING_TAIL_RE.sub("", norm)
    words = [w for w in re.split(r"[^\w/]+", norm) if w]
    kept = [w for w in words if w not in _NOISE_WORDS]
    key = _ALNUM_RE.sub("", "".join(kept))
    return key


# ---------------------------------------------------------- наименования фирм

# Одна и та же компания пишется как «СОЮЗ-ТЕХНО ООО», «ООО «Союз-Техно»» и
# «ООО Союз Техно (ИНН …)». Для сведения внешней находки со своим контрагентом
# нужен ключ, не зависящий от кавычек, дефисов, порядка слов и правовой формы.
_ORG_FORM = {
    "ооо", "оао", "зао", "пао", "ао", "ип", "тоо", "чуп", "одо",
    "фгуп", "гуп", "муп", "фгбу", "гк", "нпо", "нпф", "нпп", "пк", "тд",
    "оп", "филиал", "компания", "фирма", "предприятие",
    "ltd", "llc", "inc", "gmbh",
}
_INN_TAIL_RE = re.compile(r"\bинн\s*\d{10,12}\b", re.I)
_COMPANY_JUNK_RE = re.compile(r"[«»\"'`()\[\]]")


def company_key(name: str) -> str:
    """Ключ организации: без правовой формы, кавычек и порядка слов.

    «ООО «Союз-Техно»» и «СОЮЗ-ТЕХНО ООО» дают один ключ «союзтехно» — без
    этого внешняя находка заводила второго лида на того же покупателя.
    """
    s = normalize_name(name)
    s = _INN_TAIL_RE.sub(" ", s)
    s = _COMPANY_JUNK_RE.sub(" ", s)
    words = [w for w in re.split(r"[^\w]+", s) if w and w not in _ORG_FORM]
    return "".join(sorted(words))


# ---------------------------------------------------------------- ссылки

_URLISH_RE = re.compile(r"^[\w.-]+\.[a-z]{2,}(?:[/?#].*)?$", re.I)


def web_url(value: str | None) -> str | None:
    """Привести ссылку к абсолютному виду.

    Модель и объявления часто отдают домен без схемы — «almaz-neft.ru».
    Браузер принимает такую ссылку за путь на нашем же сервере и показывает
    «Not Found» вместо сайта покупателя. Здесь схема достраивается, а всё,
    что ссылкой не является («нет данных», телефон), отбрасывается.
    """
    s = (value or "").strip().strip("<>\"'")
    if not s or " " in s:
        return None
    low = s.lower()
    if low.startswith(("http://", "https://")):
        return s
    if low.startswith("//"):
        return "https:" + s
    if low.startswith("www.") or _URLISH_RE.match(s):
        return "https://" + s
    return None
