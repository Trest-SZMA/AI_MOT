"""Нормализация имён, классификация семейств, типоразмеры, марки лома."""
from __future__ import annotations

import re

# ---------------------------------------------------------------- нормализация


_WS_RE = re.compile(r"\s+")
_BU_RE = re.compile(r"\bб[\s./\\]*у\b\.?", re.I)
_SUFFIX_RE = re.compile(r"\s*\((?:тн|т|шт|кг|км|м)\.?\)\s*$", re.I)
# унификация разделителя размеров: 16х2,5 = 16*2.5 = 16x2.5 = 16×2.5
_SIZE_SEP_RE = re.compile(r"(?<=[\d,.])\s*[х*×x]\s*(?=\d)", re.I)
_DECIMAL_RE = re.compile(r"(?<=\d),(?=\d)")


def normalize_name(name: str) -> str:
    """Каноническая форма имени для дедупликации и матчинга."""
    s = str(name).strip().lower().replace("ё", "е").replace("\xa0", " ")
    s = _SUFFIX_RE.sub("", s)
    s = _BU_RE.sub("б/у", s)
    s = _DECIMAL_RE.sub(".", s)
    s = _SIZE_SEP_RE.sub("х", s)  # кириллическая «х» как канон
    s = _WS_RE.sub(" ", s).strip()
    return s


def tokens(name: str) -> list[str]:
    """Токены от 2 символов; типоразмеры («89», «60х5», «45-117») критичны."""
    return [t for t in re.split(r"[^\w.х-]+", normalize_name(name)) if len(t) >= 2]


