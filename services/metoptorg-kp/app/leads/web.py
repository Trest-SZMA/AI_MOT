def industries_of(profile: dict, family: str | None) -> str:
    listed = ", ".join(profile.get("industries") or [])
    return listed or FAMILY_INDUSTRIES.get(family or "", "") or "промышленность"


def find_buyers(name: str, profile: dict, family: str | None = None) -> list[dict]:
    data, urls = ai_client.ask_json(
        BUYERS_PROMPT.format(
            name=name,
            what=profile.get("what") or name,
            industries=industries_of(profile, family)),
        want_list=True)
    out = []
    for r in data if isinstance(data, list) else []:
        if not isinstance(r, dict) or not (r.get("name") or "").strip():
            continue
        out.append({"name": str(r["name"])[:200],
                    "inn": str(r.get("inn") or "")[:16],
                    "region": str(r.get("region") or "")[:120],
                    "site": web_url(r.get("site")) or "",
                    "activity": str(r.get("activity") or "")[:400],
                    "why": str(r.get("why") or "")[:600],
                    "url": web_url(r.get("url")) or ""})
    return out


def find_tenders(name: str, profile: dict, family: str | None = None) -> list[dict]:
    kw = ", ".join((profile.get("keywords") or [])[:6]) or name
    data, _ = ai_client.ask_json(
        TENDERS_PROMPT.format(name=name, keywords=kw),
        want_list=True,
        search_domains=["zakupki.gov.ru", "b2b-center.ru", "roseltorg.ru",
                        "etp-ets.ru", "tender.pro"])
    out = []
    for r in data if isinstance(data, list) else []:
        if not isinstance(r, dict) or not (r.get("customer") or "").strip():
            continue
        price = r.get("price")
        try:
            price = float(str(price).replace(" ", "").replace(",", "."))
        except (TypeError, ValueError):
            price = None
        out.append({"customer": str(r["customer"])[:200],
                    "inn": str(r.get("inn") or "")[:16],
                    "region": str(r.get("region") or "")[:120],
                    "subject": str(r.get("subject") or "")[:400],
                    "price": price,
                    "quantity": str(r.get("quantity") or "")[:80],
                    "date": str(r.get("date") or "")[:32],
                    "url": web_url(r.get("url")) or ""})
    return out
