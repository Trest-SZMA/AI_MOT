def _safe(fn, *args, **kwargs):
    """Внешний источник не должен ронять кампанию: ошибку логируем и идём дальше."""
    try:
        return fn(*args, **kwargs), None
    except AiUnavailable as e:
        return None, str(e)
    except Exception as e:  # noqa: BLE001 — модель может вернуть что угодно
        log.warning("внешний поиск не удался: %s", e)
        return None, f"{type(e).__name__}: {e}"


def product_profile(name: str, unit: str | None) -> dict:
    data, _ = ai_client.ask_json(
        PROFILE_PROMPT.format(name=name, unit=unit or "шт"))
    return data if isinstance(data, dict) else {}


