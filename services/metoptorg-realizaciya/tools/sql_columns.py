def main():
    cfg = sqlsrc.load_config()
    ok, drv = sqlsrc.driver_status()
    print("=" * 78)
    print("СВЕРКА КОЛОНОК: таблица в SQL ↔ файловая выгрузка ↔ чего ждёт расчёт")
    print("=" * 78)
    print("  %s · база %s · драйвер: %s" % (cfg.get("host"), cfg.get("database"), drv))
    beda = 0
    for key, label, _pat in sqlsrc.SOURCES:
        src = (cfg.get("sources") or {}).get(key) or {}
        table = src.get("table") or ""
        fname, fcols, frows = csv_columns(FIND.get(key, ''))
        print("\n" + "-" * 78)
        print("%s" % label)
        if not table:
            print("   таблица не указана — вход остаётся на файле %s" % (fname or "—"))
            continue
        try:
            info = sqlsrc.probe(table, cfg, limit=1)
        except Exception as e:
            print("   ❌ таблица «%s»: %s: %s" % (table, type(e).__name__, e))
            beda += 1
            continue
        scols = info["columns"]
        print("   SQL   : %-42s %8d строк · %d колонок" % (table, info["rows"], len(scols)))
        if fcols is None:
            print("   файл  : нет — сравнивать не с чем, проверьте состав глазами")
        else:
            print("   файл  : %-42s %8d строк · %d колонок" % (fname, frows, len(fcols)))
            miss = [c for c in fcols if c not in scols]
            extra = [c for c in scols if c not in fcols]
            if miss:
                beda += 1
                print("   ❌ В ТАБЛИЦЕ НЕТ КОЛОНОК, КОТОРЫЕ ЕСТЬ В ФАЙЛЕ (%d):" % len(miss))
                for c in miss[:12]:
                    print("        %s" % c)
                if len(miss) > 12:
                    print("        … ещё %d" % (len(miss) - 12))
            else:
                print("   ✅ все колонки файла в таблице есть")
            if extra:
                print("   +  в таблице добавилось (безопасно, %d): %s%s"
                      % (len(extra), ", ".join(extra[:6]), " …" if len(extra) > 6 else ""))
            if frows and abs(info["rows"] - frows) > max(50, frows * 0.05):
                print("   ⚠️ строк расходится с файлом заметно: %d против %d"
                      % (info["rows"], frows))
        need = [c for c in NEEDED.get(key, []) if c not in scols]
        if need:
            beda += 1
            print("   ❌ РАСЧЁТ СПРАШИВАЕТ, А В ТАБЛИЦЕ НЕТ: %s" % ", ".join(need))
        elif NEEDED.get(key):
            print("   ✅ все колонки, которые спрашивает расчёт, на месте")
    print("\n" + "=" * 78)
    if beda:
        print("ИТОГ: проблем %d. Включать чтение из SQL по ним НЕЛЬЗЯ — расчёт не"
              % beda)
        print("      упадёт, он молча получит пустые значения, и цифры поедут.")
        return 1
    print("ИТОГ: состав колонок сходится, можно включать чтение из SQL.")
    print("      После первой пересборки обязательно сверить §3 опорных цифр.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
