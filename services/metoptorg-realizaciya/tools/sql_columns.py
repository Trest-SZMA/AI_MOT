def csv_columns(pattern):
    """Колонки и число строк нынешней файловой выгрузки — эталон."""
    files = sorted(glob.glob(os.path.join(ROOT, "data", pattern)))
    if not files:
        return None, None, None
    path = files[-1]
    lines = read_text_lines(path)
    if not lines:
        return os.path.basename(path), [], 0
    # ⚠️ СТРОКИ СЧИТАЕМ ПАРСЕРОМ CSV, А НЕ ПО ПЕРЕВОДАМ СТРОКИ. В выгрузке
    # оплат назначение платежа содержит переносы внутри поля: файл на 4 809
    # физических строк — это 3 873 записи, и подсчёт «по строкам» поднимал
    # ложную тревогу «расходится с SQL».
    rd = csv.reader(lines)
    hdr = next(rd, [])
    n = sum(1 for _ in rd)
    return os.path.basename(path), [h.strip() for h in hdr], n


